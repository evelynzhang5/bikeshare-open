"""Verify committed metrics from saved predictions, without fitting models.

Run: python -m src.verify_results
"""
import hashlib
import json

import numpy as np
import pandas as pd

from src.config import (
    ABLATION_FEATURE, FORBIDDEN, METRICS, PREDICTIONS, RAW, RAW_SHA256,
    ROOT, SELECTED_FEATURE_SET, SELECTED_MODEL, TARGET, TRAIN_END, VALID_END,
)


def verify() -> None:
    assert hashlib.sha256(RAW.read_bytes()).hexdigest() == RAW_SHA256
    metrics = json.loads(METRICS.read_text())
    predictions = pd.read_csv(PREDICTIONS, parse_dates=["dteday"])
    raw = pd.read_csv(RAW, parse_dates=["dteday"])
    expected = raw.loc[raw.dteday > TRAIN_END, ["dteday", TARGET]].reset_index(drop=True)
    pd.testing.assert_frame_equal(
        predictions[["dteday", TARGET]], expected, check_dtype=False,
    )
    assert predictions.dteday.is_unique and predictions.dteday.is_monotonic_increasing
    expected_split = np.where(predictions.dteday <= VALID_END, "valid", "test")
    assert (predictions["split"].to_numpy() == expected_split).all()
    assert metrics["selected_feature_set"] == SELECTED_FEATURE_SET
    assert metrics["selected_model"] == SELECTED_MODEL
    assert metrics["target_transformation"] == "none"

    variants = {"before_feature": "without_feature", "after_feature": "with_feature"}
    methods = ("baseline_mean", "baseline_persistence", "ridge", "hgb")
    previous = json.loads((ROOT / "docs/evidence/validation-cnt-roll-3.json").read_text())
    checked = 0
    for variant, old_name in variants.items():
        entry = metrics[variant]
        assert entry["n_features"] == len(entry["features"])
        assert not (set(entry["features"]) & FORBIDDEN)
        assert entry["features"] == previous["variants"][old_name]["features"]
        for split in ("valid", "test"):
            part = predictions.loc[predictions["split"] == split]
            assert len(part) == entry[f"n_{split}"]
            y = part[TARGET].to_numpy(dtype=float)
            for method in methods:
                pred = part[f"{variant}__{method}"].to_numpy(dtype=float)
                assert np.isfinite(pred).all()
                actual = {
                    "r2": round(float(1 - np.square(y - pred).sum() / np.square(y - y.mean()).sum()), 4),
                    "mae": round(float(np.abs(y - pred).mean()), 1),
                }
                assert actual == entry[method][split], (variant, method, split, actual)
                if split == "valid":
                    old = previous["variants"][old_name]["metrics"][method]
                    assert actual == {"r2": round(old["r2"], 4), "mae": round(old["mae"], 1)}
                checked += 2
    before, after = (metrics[name]["features"] for name in variants)
    assert after == before + [ABLATION_FEATURE]
    for method in ("baseline_mean", "baseline_persistence"):
        np.testing.assert_array_equal(
            predictions[f"before_feature__{method}"],
            predictions[f"after_feature__{method}"],
        )
    print(f"OK raw: canonical SHA-256 unchanged; {len(predictions)} saved dates and targets match raw data")
    print(f"OK metrics: all {checked} rounded values match saved predictions")
    print("OK validation: all eight H1 rows match the earlier validation-only comparison")
    print("OK selection: fixed before_feature/ridge; candidate-only feature difference; identical baselines")
    print("No models were fitted or predictions regenerated by this verification.")


if __name__ == "__main__":
    verify()
